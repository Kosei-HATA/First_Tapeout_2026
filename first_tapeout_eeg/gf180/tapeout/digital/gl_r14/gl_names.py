#!/usr/bin/env python3
"""The flip-flop Q nets of the r14 macro's gate-level netlist that gl_shadow_r14.sv compares and forces (VER-05).

The netlist keeps RTL names on many nets, but which name a register's net carries (the submodule's port, u_seq.state,
or the top's wire, seq_state) and whether a buffer sits between the flip-flop and the named net differ from run to run.
For every register bit this finds the named net (from a list of candidates), walks up through buffers to the
flip-flop that drives it, and writes the Q net of that flip-flop: forcing that net reaches every load of the register
(through the buffers) and the flip-flop's own D logic, as a change of the register would.

usage: gl_names.py <netlist.v> <out.svh>
"""
import re
import sys

TARGETS = {          # macro: (candidate names with {k}, bits)
    "GL_ST": (["\\u_spi.st[{k}]"], 4),
    "GL_SEQ": (["\\u_seq.state[{k}]", "\\seq_state[{k}]"], 4),
    "GL_CNT": (["\\seq_cnt[{k}]"], 16),
    "GL_WE": (["reg_we", "\\u_spi.reg_we"], 1),
    "GL_ADDR": (["\\reg_addr[{k}]", "\\u_spi.reg_addr[{k}]"], 7),
    "GL_WDATA": (["\\reg_wdata[{k}]", "\\u_spi.wdat[{k}]"], 8),
}


def main():
    nl, out = sys.argv[1], sys.argv[2]
    txt = open(nl).read()
    driver = {}                    # net -> (instance, cell, pin)
    inputs = {}                    # instance -> {pin: net}
    for m in re.finditer(r"\n\s*(\w+__\w+)\s+(\S+)\s*\((.*?)\);", txt, re.S):
        cell, inst, body = m.group(1).split("__")[-1], m.group(2), m.group(3)
        pins = {p: n.strip() for p, n in re.findall(r"\.(\w+)\(([^()]*)\)", body)}
        inputs[inst] = (cell, pins)
        for p in ("Q", "Z", "ZN"):
            if p in pins:
                driver[pins[p]] = (inst, cell, p)
    wires = set(w.strip() for w in re.findall(r"^\s*wire\s+(.*?);", txt, re.M))
    lines = [f"// generated by gl_names.py from {nl}"]
    report = []
    for mac, (cands, bits) in TARGETS.items():
        nets = []
        for k in range(bits):
            name = next((c.format(k=k) for c in cands if c.format(k=k) in wires), None)
            if name is None:
                sys.exit(f"{mac}[{k}]: none of {cands} is a net of {nl}")
            n, hops = name, 0
            while True:
                if n not in driver:
                    sys.exit(f"{mac}[{k}]: {name}: no driver of {n}")
                inst, cell, pin = driver[n]
                if cell.startswith("dff"):
                    break
                if re.fullmatch(r"(clk)?buf_\d+", cell):
                    n = inputs[inst][1]["I"]
                    hops += 1
                    continue
                sys.exit(f"{mac}[{k}]: {name} is driven by {inst} ({cell}), not a flip-flop through buffers")
            nets.append(n)
            report.append(f"{mac}[{k}] = {name}" + (f" <- {hops} buffer(s) <- {n} ({inst}, {cell})" if hops else
                                                    f" ({inst}, {cell})"))
        ref = lambda n: "g." + (n + " " if n.startswith("\\") else n)   # noqa: E731
        for k, n in enumerate(nets):
            lines.append(f"`define {mac}_{k} {ref(n)}")
        lines.append(f"`define {mac} {{" + ", ".join(ref(n) for n in reversed(nets)) + "}")
    open(out, "w").write("\n".join(lines) + "\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
