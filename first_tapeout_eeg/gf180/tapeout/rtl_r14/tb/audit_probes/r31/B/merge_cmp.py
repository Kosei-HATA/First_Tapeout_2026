import sys
sys.path.insert(0, "../gf180/tapeout/rtl/spec")
import regmap as R
img = {0x00:0xE6,0x01:0x10,0x02:0x18,0x03:0xA1,0x04:0x00,0x05:0x00,0x06:0x01,0x07:0x00,0x08:0xFF,0x09:0x03,0x0A:0x03,
       0x0B:0xE8,0x0C:0x05,0x10:0x00,0x11:0x00,0x20:0,0x21:0,0x22:0,0x23:3,0x24:8,0x25:1,0x26:1,0x27:0x13,0x28:7,
       0x50:5,0x51:0,0x52:0x20,0x53:3,0x54:0x0D,0x55:1,0x60:0,0x61:0,0x62:0,0x70:0,0x71:0}
for a in range(0x20, 0x29): img[a + 0x10] = img[a]
def resp(h_):
    if not h_ & 0x80: return (0, 0)
    a = h_ & 0x7F
    if a == 0x40: return (0x08, 0x00)                  # empty word: ERR (ALERT) set, SEQ_H 0
    v = img.get(a, 0)
    return (v, R.crc8([h_, v]))
bad = n = 0
for line in open("merge_rtl.txt"):
    f = line.split()
    a, k, st, rx = int(f[0], 16), int(f[1]), int(f[2], 16), int(f[7], 16)
    h = 0x80 | a
    h_ = R._skip(h << 24, k + 1) >> 24
    b1, b2 = resp(h_)
    stream = (st << 24) | (b1 << 16) | (b2 << 8)
    pred = (R._dup(stream, k) >> 8) & 0xFFFFFF
    n += 1
    if pred != rx:
        bad += 1
        print(f"addr 0x{a:02X} k={k}: RTL host bytes {rx:06X}, merge model {pred:06X} (chip header 0x{h_:02X})")
print(f"{n} frames, {bad} differ from the merge model")
