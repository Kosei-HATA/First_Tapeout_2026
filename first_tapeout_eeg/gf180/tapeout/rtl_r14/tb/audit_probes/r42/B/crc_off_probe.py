def crc8(data, c=0):
    for d in data:
        c ^= d
        for _ in range(8):
            c = ((c << 1) ^ 0x07) & 0xFF if c & 0x80 else (c << 1) & 0xFF
    return c
# reset-value register file (r14 map), undefined -> 0x00 in a burst
R = {0x00:0xE6,0x01:0x10,0x02:0x18,0x03:0xA1,0x04:0x00,0x05:0x00,0x06:0x01,0x07:0x00,0x08:0xFF,0x09:0x03,
     0x0A:0x03,0x0B:0xE8,0x0C:0x05,0x10:0x00,0x11:0x00,
     0x20:0,0x21:0,0x22:0,0x23:3,0x24:8,0x25:1,0x26:1,0x27:0x13,0x28:7,
     0x30:0,0x31:0,0x32:0,0x33:3,0x34:8,0x35:1,0x36:1,0x37:0x13,0x38:7,
     0x40:0,0x50:5,0x51:0,0x52:0x20,0x53:3,0x54:0x0D,0x55:0,0x60:0,0x61:0,0x62:0,0x70:0,0x71:0}
def r(a): return R.get(a & 0x7F, 0)
print("CRC8(0xC0)=%02X" % crc8([0xC0]))
for a in sorted(R):
    if a == 0x40: continue
    h = 0x80 | a
    d, nxt = r(a), r(a+1)
    if crc8([h, d]) == nxt:
        print("CRC-off chip passes a CRC read of 0x%02X: data %02X, next %02X" % (a, d, nxt))
